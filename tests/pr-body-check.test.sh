#!/usr/bin/env bash
# Tests runtime/scripts/pr-body-check.py, the shape check for the PR body template
# (runtime/templates/pr-body.md, TARGET § L3 Review): a filled-in body passes; the unfilled template,
# a summary that isn't one short line, a missing or unlinked preview, sections missing or out of
# order, details not collapsed, evidence linked by branch and an over-long title all fail.
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
script="$repo_root/runtime/scripts/pr-body-check.py"
template="$repo_root/runtime/templates/pr-body.md"
source "$repo_root/tests/lib.sh"
command -v python3 >/dev/null || fail "python3 not found"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# check <name> <want exit> <body file> [problem the output must name]   ($TITLE: also check a title)
check() {
  local rc=0
  "$script" "$3" ${TITLE+"$TITLE"} >"$work/out.log" 2>&1 || rc=$?
  [ "$rc" = "$2" ] || { cat "$work/out.log" >&2; fail "$1: expected exit $2, got $rc"; }
  [ -z "${4:-}" ] || grep -qF -- "$4" "$work/out.log" || { cat "$work/out.log" >&2; fail "$1: output doesn't name '$4'"; }
  echo "ok - $1"
}
# variant <name> <python code changing s, the good body>: write the changed copy, echo its path.
variant() {
  python3 -c 'import re, sys; s = open(sys.argv[1]).read(); exec(sys.argv[3]); open(sys.argv[2], "w").write(s)' \
    "$work/good.md" "$work/$1.md" "$2"
  echo "$work/$1.md"
}

sha=0123456789abcdef0123456789abcdef01234567
cat >"$work/good.md" <<EOF
Shoppers can save a cart and come back to it on another device.

**Preview:** [the deploy comment on this PR](https://github.com/acme/shop/pull/12#issuecomment-1)

## Announcement

You can now save your cart and pick it up later on any device you sign in on.

## What you should know

- **Behaviour change:** a signed-in cart is stored on the server instead of in the browser.
- **Decisions:** carts expire after 30 days (spec: specs/saved-cart.md).
- **Changed after the go:** nothing
- **Tests deleted or loosened:** none
- **Manual steps for you:** none

## Evidence

- **Screenshots:** ![saved cart](https://github.com/acme/shop/blob/$sha/docs/shots/cart.png)
  and ![empty](https://github.com/user-attachments/assets/1b2c3d4e-0000-4000-8000-000000000000)
- **Reviewer:** pass on every lens for commit ${sha:0:7}
- **CI:** green for commit ${sha:0:7}
- **Low findings:** none

<details>
<summary>Engineering details</summary>

New \`carts\` table; the migration only adds it, so a rollback needs no database change.

</details>

---
Generated by a bot footer, allowed after the details.
EOF

check "a filled-in body passes" 0 "$work/good.md"
TITLE="Save a cart and pick it up on another device" check "a title of 72 chars or fewer passes" 0 "$work/good.md"
check "no announcement (not user-facing) passes" 0 "$(variant no-announce \
  's = s[:s.index("## Announcement")] + s[s.index("## What you should know"):]')"
check "native: no preview, simulator screenshots instead, passes" 0 "$(variant native \
  's = re.sub(r"\*\*Preview:\*\*.*", "**Preview:** none — native: simulator screenshots under Evidence", s)')"

check "the unfilled template fails" 1 "$template" "placeholder left: {{"

check "a heading as the summary fails" 1 "$(variant heading-summary 's = "# " + s')" "plain one-line summary"
check "a two-line summary fails" 1 "$(variant two-lines 's = s.replace("device.\n", "device.\nAnd more.\n", 1)')" "summary must be one line"
check "an over-long summary fails" 1 "$(variant long-summary 's = "x" * 121 + s[s.index("\n"):]')" "summary: 121 characters"
check "a missing preview fails" 1 "$(variant no-preview 's = re.sub(r"\*\*Preview:\*\*.*\n", "", s)')" "no **Preview:** line"
check "a preview without a link or a reason fails" 1 "$(variant bare-preview \
  's = re.sub(r"\*\*Preview:\*\*.*", "**Preview:** see the bot", s)')" "**Preview:** needs a link"
check "a preview below the sections fails" 1 "$(variant late-preview \
  's = re.sub(r"\*\*Preview:\*\*.*\n", "", s).replace("- **Low findings:** none", "- **Low findings:** none\n\n**Preview:** none — docs only")')" "must come before the first section"
check "evidence before what you should know fails" 1 "$(variant order \
  's = s.replace("## What you should know", "## TMP").replace("## Evidence", "## What you should know").replace("## TMP", "## Evidence")')" "sections out of order"
check "an announcement below what you should know fails" 1 "$(variant late-announce \
  'a = s[s.index("## Announcement"):s.index("## What you should know")]; s = s.replace(a, ""); s = s.replace("## Evidence", a + "## Evidence")')" "sections out of order"
check "a missing evidence section fails" 1 "$(variant no-evidence \
  's = s[:s.index("## Evidence")] + s[s.index("<details>"):]')" "missing section: ## Evidence"
check "an empty announcement fails" 1 "$(variant empty-announce \
  's = re.sub(r"You can now.*\n", "<!-- nothing -->\n", s)')" "empty section: ## Announcement"
check "an extra top-level section fails" 1 "$(variant extra 's = s.replace("## Evidence", "## Notes\n\nhi\n\n## Evidence")')" "unexpected heading: ## Notes"
check "a missing CI line in evidence fails" 1 "$(variant no-ci 's = re.sub(r"- \*\*CI:\*\*.*\n", "", s)')" "## Evidence: no **CI:** line"
check "a missing line in what you should know fails" 1 "$(variant no-tests-line \
  's = re.sub(r"- \*\*Tests deleted or loosened:\*\*.*\n", "", s)')" "no **Tests deleted or loosened:** line"
check "engineering details as a heading, not collapsed, fails" 1 "$(variant open-details \
  's = s.replace("<details>\n<summary>Engineering details</summary>", "## Engineering details").replace("</details>", "")')" "no collapsed <details>"
check "details that are never closed fail" 1 "$(variant unclosed 's = s.replace("</details>", "")')" "no collapsed <details>"
check "a heading after the details fails" 1 "$(variant after-details 's = s + "\n## More\n\ntext\n"')" "a heading after the engineering details"
check "evidence linked by branch fails (L-30)" 1 "$(variant branch-image "s = s.replace('blob/$sha', 'blob/main')")" "linked by 'main', not a commit SHA"
check "raw evidence linked by branch fails (L-30)" 1 "$(variant raw-branch-image \
  "s = s.replace('https://github.com/acme/shop/blob/$sha', 'https://raw.githubusercontent.com/acme/shop/feature/cart')")" "linked by 'feature', not a commit SHA"
check "a relative image fails" 1 "$(variant relative-image "s = s.replace('https://github.com/acme/shop/blob/$sha/', '')")" "not an absolute https URL"
TITLE=$(printf 'x%.0s' {1..73}) check "a title over 72 chars fails" 1 "$work/good.md" "title: 73 characters"

check "a missing body file fails closed" 2 "$work/nonexistent.md" "can't read"
rc=0; "$script" >"$work/out.log" 2>&1 || rc=$?
[ "$rc" = 2 ] || fail "no arguments: expected exit 2, got $rc"
echo "ok - no arguments fails closed"
echo "PASS: pr-body-check.py"
